class DERStrategy(CLStrategy):
    """DER with class-balanced reservoir sampling and normalised soft targets."""
    def __init__(self, n_classes, mode='sp_basic'):
        super().__init__(n_classes, mode)
        # FIX-T1.1: per-class sub-buffers for balanced replay
        self._per_cls = max(1, CFG['replay_size'] // n_classes)
        self._bufs    = {c: [] for c in range(n_classes)}
        self._n_seen  = {c: 0 for c in range(n_classes)}
        self._n = 0

    def _buf_flat(self):
        return [(a, lo) for b in self._bufs.values() for (a, lo) in b]

    def partial_fit(self, alpha, y):
        self._fit_one(alpha, y)
        flat = self._buf_flat()
        if flat:
            batch = min(CFG['replay_batch'], len(flat))
            idxs = np.random.choice(len(flat), batch, replace=False)
            for idx in idxs:
                a_r, lo = flat[idx]
                # FIX-T1.1: normalise logits before softmax to avoid collapse
                lo_n = lo - lo.mean()
                ls = lo_n / CFG['der_temp']; ls -= ls.max()
                sp = np.exp(ls); sp /= sp.sum()
                if self.mode == 'sp_opt':
                    self._fit_one(a_r, int(np.argmax(sp)))
                else:
                    old = self._clf.eta0
                    self._clf.eta0 = self.lr * CFG['der_alpha']
                    self._clf.partial_fit(a_r.reshape(1,-1), np.array([int(np.argmax(sp))]))
                    self._clf.eta0 = old
        if self.scaler_ready: self._store(alpha, int(y), self.logits(alpha))
        self._n += 1

    def _store(self, a, y_int, lo):
        buf = self._bufs[y_int]
        ns  = self._n_seen[y_int]
        self._n_seen[y_int] += 1
        if len(buf) < self._per_cls:
            buf.append((a.copy(), lo.copy()))
        else:
            j = np.random.randint(0, ns + 1)
            if j < self._per_cls:
                buf[j] = (a.copy(), lo.copy())

    def buf_class_hist(self):
        return {c: len(b) for c, b in self._bufs.items()}

    def on_drift(self, t):
        if self._fitted:
            for c, buf in self._bufs.items():
                self._bufs[c] = [(a, self.logits(a)) for a, _ in buf]


