class RawPCAExtractor:
    """raw_pca: whiten raw window → PCA(32) — no signal processing."""
    def __init__(self, n_components=CFG['pca_components']):
        self.n_components = n_components
        self._pca    = None
        self._scaler = StandardScaler()
        self._buf    = []
        self._fitted = False
        self._dim    = n_components

    def extract(self, window: np.ndarray) -> np.ndarray:
        """window: raw 1-D signal segment of length W (or W*n_channels)."""
        W = CFG['W']
        if len(window) > W:
            # multi-channel: stack per-channel windows and mean-pool PCA
            n_ch = len(window) // W
            vecs = []
            for ch in range(n_ch):
                seg = window[ch*W:(ch+1)*W].reshape(1, -1)
                if self._fitted:
                    seg_s = self._scaler.transform(seg)
                    vecs.append(self._pca.transform(seg_s)[0])
                else:
                    vecs.append(seg[0, :self.n_components])
            feat = np.mean(vecs, axis=0).astype(np.float32)
        else:
            seg = window.reshape(1, -1)
            if self._fitted:
                seg_s = self._scaler.transform(seg)
                feat  = self._pca.transform(seg_s)[0].astype(np.float32)
            else:
                feat = window[:self.n_components].copy().astype(np.float32)

        # Accumulate for PCA fitting
        # FIX: 50 samples is sufficient for PCA(32) on 256-dim data;
        # 200 consumed ~86% of all windows when T=30000, leaving almost nothing to train on.
        if not self._fitted:
            self._buf.append(window[:W].reshape(1, -1)[0])
            if len(self._buf) >= 50:
                X_buf = np.stack(self._buf)
                self._scaler.fit(X_buf)
                X_s = self._scaler.transform(X_buf)
                self._pca = PCA(n_components=self.n_components,
                                random_state=CFG['random_seed'])
                self._pca.fit(X_s)
                self._fitted = True
                self._buf = []
                logger.info(f'  [RawPCA] PCA fitted, '
                            f'explained var = '
                            f'{self._pca.explained_variance_ratio_.sum():.3f}')
        return feat

    @property
    def dim(self): return self._dim
    @property
    def is_fitted(self): return self._fitted


class SPExtractor:
    """sp_basic / sp_opt: DWT + STFT statistical features."""
    def __init__(self, wavelet=CFG['wavelet'], level=CFG['dwt_level'],
                 nperseg=CFG['nperseg']):
        self.wavelet = wavelet
        self.level   = level
        self.nperseg = nperseg
        self._dim    = None

    def extract(self, window: np.ndarray) -> np.ndarray:
        W = CFG['W']
        feats = []
        if len(window) > W:
            n_ch = len(window) // W
            for ch in range(n_ch):
                feats.extend(self._extract_single(window[ch*W:(ch+1)*W]))
        else:
            feats.extend(self._extract_single(window))
        vec = np.array(feats, dtype=np.float32)
        if self._dim is None:
            self._dim = len(vec)
        return vec

    def _extract_single(self, window):
        feats = []
        coeffs = pywt.wavedec(window, self.wavelet, level=self.level)
        for c in coeffs:
            feats.extend(self._stats(c))
        _, _, Zxx = scipy_stft(window, nperseg=self.nperseg)
        feats.extend(self._stats(np.abs(Zxx).flatten()))
        return feats

    def _stats(self, c):
        mu     = np.mean(c)
        var    = np.var(c)
        energy = np.sum(c**2)
        kurt   = np.mean((c-mu)**4) / (var**2 + 1e-8)
        return [mu, var, energy, kurt]

    @property
    def dim(self):
        if self._dim is None:
            self.extract(np.zeros(CFG['W']))
        return self._dim


