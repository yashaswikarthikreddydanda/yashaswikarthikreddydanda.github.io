class DatasetFactory:

    @staticmethod
    def synthetic_drift(T=50_000, fs=250, n_classes=4, n_drifts=5,
                        segment_len=2000, seed=42):
        rng = np.random.default_rng(seed)
        class_freqs = np.array([8.0, 12.0, 20.0, 30.0])
        t_arr  = np.arange(T) / fs
        signal = np.zeros(T, dtype=np.float32)
        labels = np.zeros(T, dtype=np.int32)
        n_segs = T // segment_len
        drift_segs = sorted(
            rng.choice(range(n_segs//4, 3*n_segs//4), n_drifts, replace=False))
        drift_points = [int(s * segment_len) for s in drift_segs]
        freq_shift, noise_lvl = 0.0, 0.05
        for seg in range(n_segs):
            start = seg * segment_len
            end   = min(start + segment_len, T)
            if seg in drift_segs:
                freq_shift += rng.uniform(3, 7)
                noise_lvl  += rng.uniform(0.1, 0.25)
            c     = int(rng.integers(0, n_classes))
            f     = float(class_freqs[c % len(class_freqs)]) + freq_shift
            seg_t = t_arr[start:end]
            seg_sig = (np.sin(2*np.pi*f*seg_t) +
                       0.3*np.sin(2*np.pi*2*f*seg_t) +
                       rng.normal(0, noise_lvl, end-start).astype(np.float32))
            signal[start:end] = seg_sig
            labels[start:end] = c
        X, y = DatasetFactory._segment(signal, labels, CFG['W'], CFG['S'])
        return X, y, fs, 'Synthetic', drift_points

