class OptimizedSGD:
    """
    Manual AMSGrad + Nesterov momentum + gradient clipping on top of SGDClassifier.
    SGDClassifier is used only for its log_loss forward pass and predict methods.
    All weight updates are done manually so we aren't limited by sklearn's API.
    """
    def __init__(self, n_classes, lr=CFG['lr_max']):
        self.n_classes = n_classes
        self.lr        = lr
        self._classes  = np.arange(n_classes)
        self._fitted   = False
        # Plain SGDClassifier — no momentum kwarg, we handle it ourselves
        self._clf = SGDClassifier(
            loss='log_loss',
            learning_rate='constant',
            eta0=lr,
            random_state=CFG['random_seed'],
        )
        # AMSGrad state
        self._m     = None
        self._v     = None
        self._v_hat = None
        self._step  = 0
        # Nesterov momentum buffer
        self._momentum_buf = None

    def _get_weights(self):
        if not self._fitted: return None
        return np.concatenate([self._clf.coef_.flatten(),
                               self._clf.intercept_.flatten()])

    def _set_weights(self, w):
        nc = self._clf.coef_.size
        self._clf.coef_[:]      = w[:nc].reshape(self._clf.coef_.shape)
        self._clf.intercept_[:] = w[nc:]

    def partial_fit(self, alpha, y):
        a2d = alpha.reshape(1, -1)
        y_a = np.array([int(y)])

        # First call: just fit to initialise coef_ / intercept_ shapes
        if not self._fitted:
            self._clf.partial_fit(a2d, y_a, classes=self._classes)
            self._fitted = True
            return  # skip optimiser on very first step

        # Snapshot weights before sklearn update
        w_before = self._get_weights()
        self._clf.partial_fit(a2d, y_a)
        w_after = self._get_weights()

        if w_before is None or w_after is None: return

        # Approximate gradient from SGD's own weight delta
        raw_grad = (w_before - w_after) / (self.lr + 1e-12)
        raw_grad  = np.clip(raw_grad, -10., 10.)  # pre-clip

        # Nesterov lookahead: use momentum-adjusted position for gradient
        if self._momentum_buf is None:
            self._momentum_buf = np.zeros_like(raw_grad)
        mu = CFG['momentum']
        self._momentum_buf = mu * self._momentum_buf + raw_grad
        nesterov_grad = raw_grad + mu * self._momentum_buf

        # AMSGrad update
        if self._m is None:
            self._m     = np.zeros_like(nesterov_grad)
            self._v     = np.zeros_like(nesterov_grad)
            self._v_hat = np.zeros_like(nesterov_grad)

        self._step += 1
        b1  = CFG['amsgrad_beta1']
        b2  = CFG['amsgrad_beta2']
        eps = CFG['amsgrad_eps']

        self._m = b1 * self._m + (1 - b1) * nesterov_grad
        self._v = b2 * self._v + (1 - b2) * nesterov_grad**2
        self._v_hat = np.maximum(self._v_hat, self._v)

        m_hat  = self._m / (1 - b1**self._step)  # FIX-4: removed spurious +eps
        update = self.lr * m_hat / (np.sqrt(self._v_hat) + eps)

        # Gradient clipping (L2 norm)
        norm = np.linalg.norm(update)
        if norm > CFG['grad_clip']:
            update = update * CFG['grad_clip'] / norm

        # Guard against NaN/Inf
        if not np.all(np.isfinite(update)):
            logger.warning(f'  [OptimizedSGD] Non-finite update at step {self._step}, skipping')
            self._set_weights(w_before)
            return

        self._set_weights(w_before - update)

    def predict(self, alpha):
        if not self._fitted: return 0
        return int(self._clf.predict(alpha.reshape(1, -1))[0])

    def logits(self, alpha):
        if not self._fitted: return np.zeros(self.n_classes, dtype=np.float32)
        return self._clf.decision_function(alpha.reshape(1, -1))[0].astype(np.float32)

    def predict_proba(self, alpha):
        if not self._fitted:
            return np.ones(self.n_classes) / self.n_classes
        return self._clf.predict_proba(alpha.reshape(1, -1))[0]

    def set_lr(self, lr):
        self.lr = lr
        self._clf.eta0 = lr

    def reset_amsgrad(self):
        self._m = self._v = self._v_hat = None
        self._momentum_buf = None
        self._step = 0

