class CosineLRScheduler:
    """Cosine annealing LR from lr_max → lr_min per segment; hard restart on drift."""
    def __init__(self, lr_max=CFG['lr_max'], lr_min=CFG['lr_min'], T_max=None):
        self.lr_max = lr_max; self.lr_min = lr_min
        # FIX-17: T_max=500 >> 233 total windows; 50 matches inter-drift segment length
        self.T_max  = T_max if T_max is not None else 50
        self._t     = 0

    def step(self):
        lr = self.lr_min + 0.5 * (self.lr_max - self.lr_min) * (
            1 + np.cos(np.pi * self._t / self.T_max))
        self._t = (self._t + 1) % self.T_max
        return float(lr)

    def restart(self):
        self._t = 0


