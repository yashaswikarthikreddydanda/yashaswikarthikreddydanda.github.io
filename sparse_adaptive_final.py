class SparseCoder:
    def __init__(self, method=CFG['sparse_method'],
                 sparsity=CFG['sparsity'], lasso_alpha=CFG['lasso_alpha']):
        self.method      = method
        self.sparsity    = sparsity
        self.lasso_alpha = lasso_alpha

    def encode(self, Ft: np.ndarray, Phi: np.ndarray) -> np.ndarray:
        if Ft.shape[0] != Phi.shape[0]:
            logger.error(f'  [Coder] Dim mismatch Ft={Ft.shape[0]} Phi={Phi.shape[0]}')
            return np.zeros(Phi.shape[1], dtype=np.float32)
        return self._omp(Ft, Phi) if self.method == 'omp' else self._lasso(Ft, Phi)

    def _omp(self, Ft, Phi):
        K = Phi.shape[1]
        residual = Ft.copy()
        selected, alpha, coeffs = [], np.zeros(K, dtype=np.float32), np.array([])
        for _ in range(self.sparsity):
            corr = np.abs(Phi.T @ residual)
            for s in selected: corr[s] = -np.inf
            selected.append(int(np.argmax(corr)))
            Phi_sel = Phi[:, selected]
            coeffs, _, _, _ = np.linalg.lstsq(Phi_sel, Ft, rcond=None)
            residual = Ft - Phi_sel @ coeffs
        for i, s in enumerate(selected):
            alpha[s] = float(coeffs[i]) if len(coeffs) else 0.
        return alpha

    def _lasso(self, Ft, Phi):
        m = Lasso(alpha=self.lasso_alpha, fit_intercept=False, max_iter=1000)
        m.fit(Phi, Ft)
        return m.coef_.astype(np.float32)

