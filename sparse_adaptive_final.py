class OnlineDictionary:
    def __init__(self, K=CFG['K']):
        self.K           = K
        self.d           = None
        self.Phi         = None
        self._buffer     = []
        self.update_every= 200

    def init_from_dim(self, d: int):
        if self.Phi is not None and self.d == d: return
        self.d   = d
        Phi      = np.random.randn(d, self.K).astype(np.float32)
        self.Phi = Phi / (np.linalg.norm(Phi, axis=0, keepdims=True) + 1e-8)
        self._buffer = []
        logger.info(f'  [Dict] Phi ({d},{self.K}), update_every={self.update_every}')

    def accumulate(self, Ft):
        if self.Phi is not None: self._buffer.append(Ft.copy())

    def update(self, n_iter=CFG['dict_iter']):
        if self.Phi is None or len(self._buffer) < CFG['dict_min_buf']: return
        F_batch, self._buffer = np.stack(self._buffer), []
        try:
            dl = DictionaryLearning(n_components=self.K, max_iter=n_iter,
                                    fit_algorithm='lars',
                                    transform_algorithm='omp',
                                    transform_n_nonzero_coefs=CFG['sparsity'],
                                    random_state=CFG['random_seed'])
            dl.fit(F_batch)
            new_Phi = dl.components_.T.astype(np.float32)
            new_Phi /= (np.linalg.norm(new_Phi, axis=0, keepdims=True) + 1e-8)
            coh = self._coherence(new_Phi)
            if coh <= CFG['max_coherence']:
                self.Phi = new_Phi
                logger.debug(f'  [Dict] Updated coh={coh:.3f}')
        except Exception as e:
            logger.debug(f'  [Dict] Skip: {e}')

    def _coherence(self, Phi):
        G = Phi.T @ Phi; np.fill_diagonal(G, 0.)
        return float(np.max(np.abs(G)))

    def coherence(self):
        return self._coherence(self.Phi) if self.Phi is not None else 0.

