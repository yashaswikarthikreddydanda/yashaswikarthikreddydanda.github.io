# ── Cell 11: Comprehensive Metrics

def compute_metrics(history: dict) -> dict:
    """
    Compute comprehensive metrics including per-drift breakdown and recovery.
    FIX-T1.2: recovery now correctly measures steps to regain 90% of pre-drift acc.
    FIX-T2.7: per-drift breakdown added.
    """
    acc_arr = np.array(history['accuracy'])
    fgt_arr = np.array(history['forgetting'])
    t_arr   = np.array(history['t'])

    mean_acc  = float(acc_arr.mean())
    final_acc = float(acc_arr[-1])
    mean_fgt  = float(fgt_arr.mean())
    max_fgt   = float(fgt_arr.max())

    # AUC-Acc: trapezoidal area under accuracy curve, normalised to [0,1]
    auc = float(np.trapz(acc_arr, t_arr) / (t_arr[-1] - t_arr[0] + 1e-8)) if len(t_arr) > 1 else mean_acc

    # BWT: per-drift immediate accuracy drop (negative = forgetting)
    bwt_vals, per_drift = [], []
    for dt, post in history['_post_drift_acc'].items():
        pre = history['_pre_drift_acc'].get(dt)
        if pre is None or len(post) < 2: continue
        imm  = float(np.mean(post[:min(5, len(post))]))
        drop = imm - pre
        bwt_vals.append(drop)
        # FIX-T1.2: recovery = eval steps until acc >= 90% of pre-drift level
        thresh = 0.9 * pre
        rec = next((i for i, v in enumerate(post) if v >= thresh), None)
        # Also record peak recovery (max acc in post window)
        peak_rec = float(max(post)) if post else pre
        per_drift.append(dict(
            drift_t   = dt,
            pre_acc   = round(pre, 4),
            imm_acc   = round(imm, 4),
            drop      = round(drop, 4),
            recovery_steps = rec,          # None = not recovered in window
            peak_recovery  = round(peak_rec, 4),
        ))
    bwt = float(np.mean(bwt_vals)) if bwt_vals else 0.

    # Recovery: only count drifts where drop was meaningful (>5%)
    speeds = [d['recovery_steps'] for d in per_drift
              if d['recovery_steps'] is not None and d['drop'] < -0.05]
    mean_rec = float(np.mean(speeds)) if speeds else None

    # FWT: zero-shot accuracy before any training on new distribution
    fwt_vals = [v for _, v in history.get('fwt_samples', [])]
    fwt = float(np.mean(fwt_vals)) if fwt_vals else None

    # Stability-Plasticity Score
    sp_score = (1 - mean_fgt) * mean_acc

    return dict(
        mean_acc    = round(mean_acc, 4),
        final_acc   = round(final_acc, 4),
        mean_fgt    = round(mean_fgt, 4),
        max_fgt     = round(max_fgt, 4),
        auc_acc     = round(auc, 4),
        bwt         = round(bwt, 4),
        fwt         = round(fwt, 4) if fwt is not None else None,
        sp_score    = round(sp_score, 4),
        n_drifts    = len(history['drift_times']),
        mean_rec    = mean_rec,
        per_drift   = per_drift,           # FIX-T2.7: per-drift breakdown
    )


def print_summary(history, dataset_name, strategy, mode):
    m = compute_metrics(history)
    triggers = history.get('drift_triggers', [])
    from collections import Counter
    trig_str = ', '.join(f'{k}={v}' for k,v in Counter(triggers).items()) if triggers else 'none'
    print(f'\n{"="*64}')
    print(f'  {dataset_name} | {strategy.upper()} | {MODE_LABELS[mode]}')
    print(f'{"="*64}')
    print(f'  Mean Accuracy         : {m["mean_acc"]:.4f}')
    print(f'  Final Accuracy        : {m["final_acc"]:.4f}')
    print(f'  AUC-Accuracy          : {m["auc_acc"]:.4f}')
    print(f'  BWT (backward trans.) : {m["bwt"]:.4f}  (negative = forgetting)')
    print(f'  FWT (forward trans.)  : {m["fwt"] if m["fwt"] is not None else "N/A"}')
    print(f'  Stab-Plast Score      : {m["sp_score"]:.4f}')
    print(f'  Mean Forgetting       : {m["mean_fgt"]:.4f}')
    print(f'  Max  Forgetting       : {m["max_fgt"]:.4f}')
    rec_str = f'{m["mean_rec"]:.1f} eval-steps' if m["mean_rec"] is not None else 'N/A (no significant drops recovered)'
    print(f'  Mean Recovery         : {rec_str}')
    print(f'  Drifts Detected       : {m["n_drifts"]}  [{trig_str}]')
    # Per-drift breakdown
    if m['per_drift']:
        print(f'  ── Per-drift breakdown ──────────────────────────────')
        for i, d in enumerate(m['per_drift']):
            rec = f'{d["recovery_steps"]} steps' if d["recovery_steps"] is not None else 'not recovered'
            print(f'    Drift {i+1} (t={d["drift_t"]:4d}): '
                  f'pre={d["pre_acc"]:.3f} → imm={d["imm_acc"]:.3f} '
                  f'(drop={d["drop"]:+.3f})  recovery={rec}')
    print(f'{"="*64}')
    return m

print('Metrics engine ready ✓  (BWT, FWT, AUC-Acc, SP-Score, per-drift breakdown)')

# ── Cell 12: Experiment Runner

def run_one(dataset='synthetic', strategy='replay', mode='sp_basic',
            verbose=True, seed=None, **kwargs):
    """Run a single experiment. seed overrides CFG random_seed for variance runs."""
    loaders = dict(synthetic=DatasetFactory.synthetic_drift,
                   physionet=DatasetFactory.physionet)
    if dataset not in loaders:
        raise ValueError(f'Unknown dataset: {dataset}')
    if seed is not None:
        np.random.seed(seed)
        if 'seed' in kwargs: kwargs.pop('seed')
    X, y, fs, name, drift_pts = loaders[dataset](**kwargs)
    n_classes = int(y.max()) + 1
    pipeline  = SparseAdaptivePipeline(
        n_classes=n_classes, strategy=strategy, mode=mode, verbose=verbose)
    history   = pipeline.run(X, y, true_drift_times=drift_pts)
    metrics   = print_summary(history, name, strategy, mode)
    return history, metrics


def run_full_comparison(dataset='synthetic', verbose=False, n_seeds=1, **kwargs):
    """
    Run 3 strategies × 3 modes = 9 experiments.
    If n_seeds > 1, repeats each run with different seeds and reports mean ± std.
    Returns: results[mode][strategy] = {'history', 'metrics', 'all_metrics'}
    """
    results = {m: {} for m in MODES}
    total   = len(MODES) * len(STRATEGIES)
    done    = 0
    failed  = []
    seeds   = [CFG['random_seed'] + i * 7 for i in range(n_seeds)]

    for mode in MODES:
        for strat in STRATEGIES:
            done += 1
            print(f'\n[{done}/{total}]  mode={MODE_LABELS[mode]}  '
                  f'strategy={strat.upper()}  dataset={dataset}'
                  + (f'  ({n_seeds} seeds)' if n_seeds > 1 else ''))
            try:
                all_m, last_h = [], None
                for s in seeds:
                    h, m = run_one(dataset=dataset, strategy=strat,
                                   mode=mode, verbose=verbose, seed=s, **kwargs)
                    all_m.append(m); last_h = h

                # Aggregate across seeds
                if n_seeds > 1:
                    agg = {}
                    scalar_keys = ['mean_acc','final_acc','mean_fgt','max_fgt',
                                   'auc_acc','bwt','sp_score','n_drifts']
                    for k in scalar_keys:
                        vals = [mm[k] for mm in all_m if mm[k] is not None]
                        agg[k]         = round(float(np.mean(vals)), 4)
                        agg[k+'_std']  = round(float(np.std(vals)), 4)
                    agg['fwt']      = all_m[-1]['fwt']
                    agg['mean_rec'] = all_m[-1]['mean_rec']
                    agg['per_drift']= all_m[-1]['per_drift']
                    m = agg
                    std_str = f'  ±std mean_acc={agg["mean_acc_std"]:.3f}'
                else:
                    std_str = ''

                results[mode][strat] = {'history': last_h, 'metrics': m,
                                        'all_metrics': all_m}
                print(f'  ✓  mean_acc={m["mean_acc"]:.3f}{std_str}  '
                      f'sp_score={m["sp_score"]:.3f}  drifts={m["n_drifts"]}')
            except Exception as e:
                import traceback
                msg = traceback.format_exc()
                logger.error(f'\n  ✗  FAILED [{mode}|{strat}]:\n{msg}')
                failed.append((mode, strat, str(e)))
                results[mode][strat] = {'history': None, 'metrics': None, 'all_metrics': []}

    print(f'\n{"="*60}')
    print(f'  Completed {done - len(failed)}/{total} runs successfully.')
    if failed:
        for mode, strat, err in failed:
            print(f'    FAILED [{mode}|{strat}] → {err[:120]}')
    print(f'{"="*60}')
    return results

print('run_one() and run_full_comparison() ready ✓  (variance runs, per-drift, recovery fixed)')

