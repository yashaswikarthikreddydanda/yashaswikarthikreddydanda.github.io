class CLStrategy:
    def __init__(self, n_classes, mode='sp_basic', lr=CFG['lr']):
        self.n_classes    = n_classes
        self.mode         = mode
        self.lr           = lr
        self._classes     = np.arange(n_classes)
        self._fitted      = False
        self.scaler_ready = False
        self._clf, self._scheduler = self._make_clf()

    def _make_clf(self):
        if self.mode == 'sp_opt':
            clf = OptimizedSGD(self.n_classes, lr=CFG['lr_max'])
            sch = CosineLRScheduler(lr_max=CFG['lr_max'], lr_min=CFG['lr_min'])
        else:
            clf = SGDClassifier(loss='log_loss', learning_rate='constant',
                                eta0=self.lr, random_state=CFG['random_seed'])
            sch = None
        return clf, sch

    def _fit_one(self, alpha, y):
        # FIX: clip sparse code to prevent SGD overflow when unscaled features
        # produce large OMP coefficients (DWT/STFT energy terms can be huge).
        alpha = np.clip(alpha, -50.0, 50.0)
        if self.mode == 'sp_opt':
            if self._scheduler:
                self._clf.set_lr(self._scheduler.step())
            self._clf.partial_fit(alpha, int(y))
            self._fitted = True
        else:
            a2d = alpha.reshape(1,-1); y_a = np.array([int(y)])
            if not self._fitted:
                self._clf.partial_fit(a2d, y_a, classes=self._classes)
                self._fitted = True
            else:
                self._clf.partial_fit(a2d, y_a)

    def predict(self, alpha):
        alpha = np.clip(alpha, -50.0, 50.0)
        if not self._fitted: return 0
        if self.mode == 'sp_opt': return self._clf.predict(alpha)
        return int(self._clf.predict(alpha.reshape(1,-1))[0])

    def logits(self, alpha):
        alpha = np.clip(alpha, -50.0, 50.0)
        if not self._fitted: return np.zeros(self.n_classes, dtype=np.float32)
        if self.mode == 'sp_opt': return self._clf.logits(alpha)
        return self._clf.decision_function(alpha.reshape(1,-1))[0].astype(np.float32)

    def predict_proba(self, alpha):
        alpha = np.clip(alpha, -50.0, 50.0)
        if not self._fitted: return np.ones(self.n_classes)/self.n_classes
        if self.mode == 'sp_opt': return self._clf.predict_proba(alpha)
        return self._clf.predict_proba(alpha.reshape(1,-1))[0]

    def boost_lr(self, factor=CFG['lr_boost']):
        if self.mode == 'sp_opt':
            if self._scheduler: self._scheduler.restart()
            if hasattr(self._clf, 'reset_amsgrad'): self._clf.reset_amsgrad()
        else:
            self.lr = min(self.lr * factor, 0.5)
            self._clf.eta0 = self.lr

    def partial_fit(self, alpha, y): raise NotImplementedError
    def on_drift(self, t): pass


