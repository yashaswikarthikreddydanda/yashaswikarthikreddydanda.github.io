class CLStrategy:
    def __init__(self, n_classes, mode='sp_basic', lr=CFG['lr']):
        self.n_classes    = n_classes
        self.mode         = mode
        self.lr           = lr
        self._classes     = np.arange(n_classes)
        self._fitted      = False
        self.scaler_ready = False
        self._clf, self._scheduler = self._make_clf()

    def _make_clf(self):
        if self.mode == 'sp_opt':
            clf = OptimizedSGD(self.n_classes, lr=CFG['lr_max'])
            sch = CosineLRScheduler(lr_max=CFG['lr_max'], lr_min=CFG['lr_min'])
        else:
            clf = SGDClassifier(loss='log_loss', learning_rate='constant',
                                eta0=self.lr, random_state=CFG['random_seed'])
            sch = None
        return clf, sch

    def _fit_one(self, alpha, y):
        # FIX: clip sparse code to prevent SGD overflow when unscaled features
        # produce large OMP coefficients (DWT/STFT energy terms can be huge).
        alpha = np.clip(alpha, -50.0, 50.0)
        if self.mode == 'sp_opt':
            if self._scheduler:
                self._clf.set_lr(self._scheduler.step())
            self._clf.partial_fit(alpha, int(y))
            self._fitted = True
        else:
            a2d = alpha.reshape(1,-1); y_a = np.array([int(y)])
            if not self._fitted:
                self._clf.partial_fit(a2d, y_a, classes=self._classes)
                self._fitted = True
            else:
                self._clf.partial_fit(a2d, y_a)

    def predict(self, alpha):
        alpha = np.clip(alpha, -50.0, 50.0)
        if not self._fitted: return 0
        if self.mode == 'sp_opt': return self._clf.predict(alpha)
        return int(self._clf.predict(alpha.reshape(1,-1))[0])

    def logits(self, alpha):
        alpha = np.clip(alpha, -50.0, 50.0)
        if not self._fitted: return np.zeros(self.n_classes, dtype=np.float32)
        if self.mode == 'sp_opt': return self._clf.logits(alpha)
        return self._clf.decision_function(alpha.reshape(1,-1))[0].astype(np.float32)

    def predict_proba(self, alpha):
        alpha = np.clip(alpha, -50.0, 50.0)
        if not self._fitted: return np.ones(self.n_classes)/self.n_classes
        if self.mode == 'sp_opt': return self._clf.predict_proba(alpha)
        return self._clf.predict_proba(alpha.reshape(1,-1))[0]

    def boost_lr(self, factor=CFG['lr_boost']):
        if self.mode == 'sp_opt':
            if self._scheduler: self._scheduler.restart()
            if hasattr(self._clf, 'reset_amsgrad'): self._clf.reset_amsgrad()
        else:
            self.lr = min(self.lr * factor, 0.5)
            self._clf.eta0 = self.lr

    def partial_fit(self, alpha, y): raise NotImplementedError
    def on_drift(self, t): pass


# ── Replay ────────────────────────────────────────────────────────────────
class ReplayStrategy(CLStrategy):
    def __init__(self, n_classes, mode='sp_basic'):
        super().__init__(n_classes, mode)
        self._per_cls = max(1, CFG['replay_size'] // n_classes)
        self._bufs    = {c: [] for c in range(n_classes)}
        self._n_seen  = 0

    def partial_fit(self, alpha, y):
        self._fit_one(alpha, y)
        items = self._sample()
        if items:
            if self.mode == 'sp_opt':
                for a_r, y_r in items: self._fit_one(a_r, y_r)
            else:
                old = self._clf.eta0
                self._clf.eta0 = self.lr * CFG['replay_lambda']
                for a_r, y_r in items:
                    self._clf.partial_fit(a_r.reshape(1,-1), np.array([y_r]))
                self._clf.eta0 = old
        buf = self._bufs[int(y)]
        if len(buf) < self._per_cls: buf.append((alpha.copy(), int(y)))
        else:
            j = np.random.randint(0, max(1, self._n_seen//self.n_classes+1))
            if j < self._per_cls: buf[j] = (alpha.copy(), int(y))
        self._n_seen += 1

    def _sample(self):
        all_i = [i for b in self._bufs.values() for i in b]
        if not all_i: return []
        idxs = np.random.choice(len(all_i), min(CFG['replay_batch'],len(all_i)), replace=False)
        return [all_i[i] for i in idxs]

    def on_drift(self, t):
        # FIX: don't reset classifier — that destroys all learned weights and causes
        # catastrophic forgetting on every drift. Just prune old replay buffer entries
        # and let boost_lr() (called by the pipeline) handle the LR increase.
        keep = CFG['replay_keep_frac']
        self._bufs = {
            c: b[-max(1, int(len(b) * keep)):]
            for c, b in self._bufs.items()
        }
        self._n_seen = 0


# ── EWC ──────────────────────────────────────────────────────────────────
class EWCStrategy(CLStrategy):
    def __init__(self, n_classes, mode='sp_basic'):
        super().__init__(n_classes, mode)
        self._anchors    = []
        self._recent_buf = []

    def _get_w(self):
        if not self._fitted: return None
        if self.mode == 'sp_opt':
            return np.concatenate([self._clf._clf.coef_.flatten(),
                                   self._clf._clf.intercept_.flatten()])
        return np.concatenate([self._clf.coef_.flatten(),
                               self._clf.intercept_.flatten()])

    def _set_w(self, w):
        if self.mode == 'sp_opt':
            clf = self._clf._clf
        else:
            clf = self._clf
        nc = clf.coef_.size
        clf.coef_[:]      = w[:nc].reshape(clf.coef_.shape)
        clf.intercept_[:] = w[nc:]

    def _fisher(self):
        if not self.scaler_ready or not self._fitted or not self._recent_buf:
            return None
        w0 = self._get_w(); n_w = len(w0); F = np.zeros(n_w, np.float64)
        eps = 1e-4; step = max(1, n_w//20)
        for a_r, y_r in self._recent_buf:
            grad = np.zeros(n_w)
            for i in range(0, n_w, step):
                wp = w0.copy(); wp[i] += eps; self._set_w(wp)
                pp = self.predict_proba(a_r)[int(y_r)]
                wm = w0.copy(); wm[i] -= eps; self._set_w(wm)
                pm = self.predict_proba(a_r)[int(y_r)]
                grad[i] = (np.log(pp+1e-8) - np.log(pm+1e-8)) / (2*eps)
            F += grad**2; self._set_w(w0)
        return np.clip(F/len(self._recent_buf), 0, CFG['ewc_fisher_clip']).astype(np.float32)

    def partial_fit(self, alpha, y):
        self._fit_one(alpha, y)
        self._recent_buf.append((alpha.copy(), int(y)))
        if len(self._recent_buf) > CFG['ewc_fisher_n']: self._recent_buf.pop(0)
        if self._fitted and self._anchors and self.scaler_ready:  # FIX: skip EWC correction when features aren't scaled yet
            w = self._get_w()
            if not np.all(np.isfinite(w)): return  # FIX: guard against overflow state
            corr = np.zeros_like(w)
            for ts, fi in self._anchors:
                if len(ts) == len(w): corr += CFG['ewc_lambda'] * fi * (w - ts)
            corr = np.clip(corr, -1., 1.)
            new_w = np.clip(w - self.lr * corr, -1e3, 1e3)  # FIX: clamp weights to prevent overflow
            self._set_w(new_w)

    def on_drift(self, t):
        if not self._fitted: return
        fi = self._fisher()
        if fi is not None:
            self._anchors.append((self._get_w().copy(), fi))
            if len(self._anchors) > 3: self._anchors.pop(0)
        self.lr = CFG['lr'] * CFG['lr_boost']
        if self.mode != 'sp_opt': self._clf.eta0 = self.lr


