class DriftDetector:
    def __init__(self):
        self.delta    = CFG['ph_delta']
        self.lam      = CFG['ph_lambda']
        self.warmup   = CFG['warmup']
        self.cooldown = CFG['drift_cooldown']
        self._m = self._mu = 0.
        self._n = 0
        self._err_buf     = deque(maxlen=CFG['ph_smooth'])
        self._win1        = deque(maxlen=50)
        self._win2        = deque(maxlen=50)
        self._win1_count  = 0
        self._steps_ph    = self.cooldown
        self._steps_ema   = CFG['ema_cooldown']
        self._ema_val     = None
        self._ema_peak    = 0.
        self._ema_peak_hist = deque(maxlen=CFG['ema_peak_window'])
        self.drift_detected    = False
        self.last_trigger_type = None

    def update(self, error: float, accuracy: float = None) -> bool:
        self._err_buf.append(error)
        smoothed = float(np.mean(self._err_buf))
        self._n  += 1
        self._mu += (smoothed - self._mu) / self._n
        self._m   = max(0., self._m + smoothed - self._mu - self.delta)
        self.drift_detected = False
        self.last_trigger_type = None
        self._steps_ph  += 1
        self._steps_ema += 1
        ph_ready  = self._steps_ph  >= self.cooldown
        ema_ready = self._steps_ema >= CFG['ema_cooldown']

        # Page-Hinkley
        if ph_ready and self._n > self.warmup and self._m > self.lam:
            self.drift_detected    = True
            self.last_trigger_type = 'ph'
            self._m = 0.; self._steps_ph = 0

        # Mean-shift (FIX-C)
        self._win1.append(smoothed); self._win1_count += 1
        if self._win1_count >= 50:
            self._win2 = deque(self._win1, maxlen=50)
            self._win1.clear(); self._win1_count = 0
        if (ph_ready and not self.drift_detected
                and len(self._win2)==50 and len(self._win1)>5
                and abs(np.mean(self._win1)-np.mean(self._win2)) > 0.15):  # raised from 0.12
            self.drift_detected    = True
            self.last_trigger_type = 'mean_shift'
            self._steps_ph = 0
            self._m = 0.  # FIX: also reset PH stat to avoid immediate re-trigger

        # EMA slow-drift (FIX-O)
        if accuracy is not None and self._n > self.warmup:
            if self._ema_val is None: self._ema_val = accuracy
            else: self._ema_val = CFG['ema_alpha']*accuracy + (1-CFG['ema_alpha'])*self._ema_val
            self._ema_peak_hist.append(self._ema_val)
            self._ema_peak = max(self._ema_peak_hist)
            drop = self._ema_peak - self._ema_val
            if (ema_ready and not self.drift_detected
                    and drop > CFG['ema_drop_thresh'] and self._ema_peak > 0.6):
                self.drift_detected    = True
                self.last_trigger_type = 'ema'
                self._steps_ema = 0; self._steps_ph = 0
        return self.drift_detected

    def reset_ema_peak(self):
        self._ema_peak = self._ema_val or 0.
        self._ema_peak_hist = deque([self._ema_peak], maxlen=CFG['ema_peak_window'])

