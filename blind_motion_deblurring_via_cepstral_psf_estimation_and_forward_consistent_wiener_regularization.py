# ─────────────────────────────────────────────────────────────────────────────
# Wiener Deblurring with Cepstrum-estimated PSF
# Three variants to isolate where quality is lost:
#   (a) true PSF + oracle K   → upper bound
#   (b) cep PSF  + oracle K   → cost of PSF estimation error
#   (c) cep PSF  + blind K    → fully blind pipeline
# ─────────────────────────────────────────────────────────────────────────────

def wiener_oracle_K(g, psf, f_ref, K_range=np.logspace(-4, -1, 40)):
    best_K, best_p, best_rec = None, -np.inf, None
    for K in K_range:
        rec = wiener(g, psf, K)
        p   = psnr(f_ref, rec)
        if p > best_p:
            best_p, best_K, best_rec = p, K, rec
    return best_rec, best_K, best_p

def wiener_blind_K(g, psf, K_range=np.logspace(-4, -1, 40)):
    """
    Blind K: pick K minimising forward-model residual ||h*wiener(g,h,K) - g||.
    No f_true needed.
    """
    best_K, best_score, best_rec = None, -np.inf, None
    for K in K_range:
        rec   = wiener(g, psf, K)
        score = -np.linalg.norm(
            ndimage.convolve(rec, psf, mode='wrap') - g
        ) / (np.linalg.norm(g) + 1e-8)
        if score > best_score:
            best_score, best_K, best_rec = score, K, rec
    return best_rec, best_K

