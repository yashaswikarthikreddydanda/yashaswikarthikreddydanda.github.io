def load_image():
    img = color.rgb2gray(data.astronaut()).astype(np.float64)
    return img / img.max()

def make_motion_psf(length=25, angle=45.0, size=None):
    if size is None:
        size = length + 4 if length % 2 == 0 else length + 3
    psf = np.zeros((size, size))
    cx, cy = size // 2, size // 2
    angle_rad = np.deg2rad(angle)
    for t in np.linspace(-(length-1)/2, (length-1)/2, length*4):
        x = int(round(cx + t * np.cos(angle_rad)))
        y = int(round(cy + t * np.sin(angle_rad)))
        if 0 <= x < size and 0 <= y < size:
            psf[y, x] = 1.0
    return psf / psf.sum()

def degrade(img, psf, sigma=0.01):
    blurred = ndimage.convolve(img, psf, mode='wrap')
    return np.clip(blurred + np.random.normal(0, sigma, img.shape), 0, 1)

def psf_to_otf(psf, shape):
    pad = np.zeros(shape)
    ph, pw = psf.shape
    pad[:ph, :pw] = psf
    pad = np.roll(pad, (-ph//2, -pw//2), axis=(0, 1))
    return fft2(pad)

def wiener(g, psf, K=1e-3):
    G = fft2(g)
    H = psf_to_otf(psf, g.shape)
    return np.clip(np.real(ifft2((np.conj(H) / (np.abs(H)**2 + K)) * G)), 0, 1)

