# Shared helper: angular error (handles 180° ambiguity in line orientation)
# ─────────────────────────────────────────────────────────────────────────────

def angle_err(est, true):
    """Smallest angular difference accounting for 180° line symmetry."""
    d = abs(est - true) % 180
    return min(d, 180 - d)

def psf_l2(h_est, h_true):
    """L2 distance between two PSFs normalised to the same canvas."""
    return np.linalg.norm(h_est - h_true)


# ─────────────────────────────────────────────────────────────────────────────
# Method 1 — Radon on log-spectrum
# ─────────────────────────────────────────────────────────────────────────────

def estimate_psf_radon(g, psf_size, sigma_noise=0.01):
    H, W = g.shape
    cy, cx = H // 2, W // 2

    G_mag = np.abs(fftshift(fft2(g)))
    G_log = np.log1p(G_mag)
    mask_r = max(int(0.03 * min(H, W)), 3)
    G_log[cy-mask_r:cy+mask_r, cx-mask_r:cx+mask_r] = 0.0
    G_log = (G_log - G_log.min()) / (G_log.max() - G_log.min() + 1e-8)

    crop_sz = min(H, W, 256)
    r0 = cy - crop_sz // 2; c0 = cx - crop_sz // 2
    G_crop = G_log[r0:r0+crop_sz, c0:c0+crop_sz]

    thetas = np.arange(0, 180, 1, dtype=float)
    sino   = radon(G_crop, theta=thetas, circle=True)

    # Min-variance column = projection along null stripes = blur direction
    col_vars     = sino.var(axis=0)
    best_ang_idx = int(np.argmin(col_vars))
    theta_est    = thetas[best_ang_idx]

    # Estimate L: slice log-spectrum along blur direction, find first null
    half  = crop_sz // 2
    t_vals = np.arange(-half, half)
    ang_r  = np.deg2rad(theta_est)
    xs = (cx - c0) + t_vals * np.cos(ang_r)
    ys = (cy - r0) + t_vals * np.sin(ang_r)
    valid = (xs >= 0) & (xs < crop_sz) & (ys >= 0) & (ys < crop_sz)
    xs, ys, t_vals = xs[valid], ys[valid], t_vals[valid]
    profile = G_crop[np.round(ys).astype(int), np.round(xs).astype(int)]
    freq    = np.abs(t_vals) / crop_sz

    inv_profile = profile.max() - profile
    peaks_idx, _ = find_peaks(inv_profile,
                               height=0.1 * inv_profile.max(), distance=3)
    peaks_idx = peaks_idx[freq[peaks_idx] > 0.02]
    if len(peaks_idx) > 0:
        L_est = int(round(1.0 / (2.0 * freq[peaks_idx[0]] + 1e-8)))
    else:
        cum = np.cumsum(profile[len(profile)//2:])
        cum /= cum[-1] + 1e-8
        idx90 = int(np.searchsorted(cum, 0.90))
        L_est = max(5, int(round(crop_sz / (2 * max(idx90, 1)))))

    L_est = int(np.clip(L_est, 3, psf_size - 2))
    return make_motion_psf(L_est, theta_est, size=psf_size), L_est, theta_est


# ─────────────────────────────────────────────────────────────────────────────
# Method 2 — Cepstrum
# ─────────────────────────────────────────────────────────────────────────────

def estimate_psf_cepstrum(g, psf_size, sigma_noise=0.01):
    H, W = g.shape
    cy, cx = H // 2, W // 2

    # Power cepstrum: IFFT of log(|FFT(g)|^2)
    G_mag2 = np.abs(fft2(g)) ** 2
    log_ps = np.log(G_mag2 + 1e-10)
    cepstrum = np.real(ifft2(log_ps))
    cepstrum = fftshift(cepstrum)

    # Suppress DC and near-DC (centre region)
    mask_r = max(int(0.04 * min(H, W)), 5)
    cep_masked = cepstrum.copy()
    cep_masked[cy-mask_r:cy+mask_r, cx-mask_r:cx+mask_r] = 0.0

    # Suppress edges (wrap-around artifacts)
    edge = max(int(0.1 * min(H, W)), 10)
    cep_masked[:edge, :] = 0; cep_masked[-edge:, :] = 0
    cep_masked[:, :edge] = 0; cep_masked[:, -edge:] = 0

    # Motion blur → two symmetric peaks at (±dy, ±dx) from centre
    # Only search upper half to avoid duplicate
    search = cep_masked.copy()
    search[cy:, :] = 0   # upper half only

    peak_idx = np.unravel_index(np.argmax(np.abs(search)), search.shape)
    dy = cy - peak_idx[0]   # row offset from centre
    dx = peak_idx[1] - cx   # col offset from centre

    L_est     = int(round(np.sqrt(dx**2 + dy**2)))
    theta_raw = np.degrees(np.arctan2(dy, dx)) % 180
    L_est     = int(np.clip(L_est, 3, psf_size - 2))

    # Resolve 180 deg ambiguity: try theta, theta+90, theta-90
    # Score each via forward consistency — correct PSF reconstructs g better
    K = sigma_noise ** 2 * 50
    candidates = [theta_raw, (theta_raw + 90) % 180, (theta_raw - 90) % 180]
    best_psf, best_theta, best_score = None, theta_raw, np.inf
    for th in candidates:
        h_try = make_motion_psf(L_est, th, size=psf_size)
        f_try = wiener(g, h_try, K=K)
        score = np.linalg.norm(ndimage.convolve(f_try, h_try, mode="wrap") - g)
        if score < best_score:
            best_score, best_theta, best_psf = score, th, h_try
    return best_psf, L_est, best_theta


# ─────────────────────────────────────────────────────────────────────────────
# Method 3 — Gradient histogram (θ) + consistency sweep (L + fine θ)
# ─────────────────────────────────────────────────────────────────────────────

def estimate_psf_grad_sweep(g, psf_size, sigma_noise=0.01,
                             L_range=range(5, 40, 2),
                             theta_coarse_step=15):
    # ── Step A: gradient histogram → blur angle ───────────────────────────
    # Motion blur suppresses gradients perpendicular to blur direction.
    # The *depleted* orientation bin in the gradient histogram = blur angle.
    gx = sobel_v(g)   # horizontal gradient (d/dx)
    gy = sobel_h(g)   # vertical gradient   (d/dy)
    mag   = np.sqrt(gx**2 + gy**2)
    # Only use strong gradients (top 30%) — weak ones are noise
    thresh = np.percentile(mag, 70)
    mask   = mag > thresh
    angles = np.degrees(np.arctan2(gy[mask], gx[mask])) % 180

    # Histogram over [0, 180)
    n_bins = 36
    hist, bin_edges = np.histogram(angles, bins=n_bins, range=(0, 180))
    bin_centres = (bin_edges[:-1] + bin_edges[1:]) / 2

    # Smooth histogram to avoid bin-edge sensitivity
    from scipy.ndimage import uniform_filter1d
    hist_smooth = uniform_filter1d(hist.astype(float), size=3, mode='wrap')

    # Blur direction = bin with minimum gradient energy (depleted orientation)
    theta_coarse = float(bin_centres[np.argmin(hist_smooth)])

    # ── Step B: forward-model consistency sweep ───────────────────────────
    # Search L × fine-θ grid around the gradient estimate.
    # Score = ||convolve(wiener(g, h), h) - g||  (blind, no f_true needed)
    theta_fine_range = np.arange(theta_coarse - 20,
                                  theta_coarse + 21,
                                  5)

    best_L, best_theta, best_score = 5, theta_coarse, np.inf
    K = sigma_noise ** 2 * 50   # fixed Wiener K for scoring

    for L_try in L_range:
        for th_try in theta_fine_range:
            h_try  = make_motion_psf(L_try, th_try % 180, size=psf_size)
            f_try  = wiener(g, h_try, K=K)
            score  = np.linalg.norm(
                ndimage.convolve(f_try, h_try, mode='wrap') - g
            )
            if score < best_score:
                best_score = score
                best_L, best_theta = L_try, th_try % 180

    return (make_motion_psf(best_L, best_theta, size=psf_size),
            best_L, best_theta)


