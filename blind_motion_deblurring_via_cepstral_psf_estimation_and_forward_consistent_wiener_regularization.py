def highlight_best(df):
    styled = df.copy().astype(str)
    for case in df['Case'].unique():
        mask = df['Case'] == case
        for metric in ['PSNR', 'SSIM']:
            best_idx = df.loc[mask, metric].idxmax()
            styled.loc[best_idx, metric] = f"✦ {df.loc[best_idx, metric]}"
    return styled

