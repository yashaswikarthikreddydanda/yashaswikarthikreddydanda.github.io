import bm3d
from skimage.restoration import denoise_tv_chambolle, denoise_bilateral
from skimage.filters import unsharp_mask

def post_process(rec, sigma_est=0.02):
    """Apply TV, Bilateral, and BM3D to a Wiener-deblurred image."""
    tv       = denoise_tv_chambolle(rec, weight=0.08)
    tv       = unsharp_mask(tv, radius=2.0, amount=1)
    bilat    = denoise_bilateral(rec, sigma_color=0.05, sigma_spatial=2)
    bm3d_out = bm3d.bm3d(rec, sigma_psd=sigma_est, stage_arg=bm3d.BM3DStages.ALL_STAGES)
    bm3d_out = np.clip(bm3d_out, 0, 1)
    return tv, bilat, bm3d_out

